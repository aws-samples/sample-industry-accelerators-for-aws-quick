"""Sandbox environment layers: validation, dependency locks, and the catalog agents choose environments from.

Each directory under `environments/` is one layer. Its `pyproject.toml` lists the layer's own direct packages (exact
pins) and, under `[tool.code-sandbox]`, its parent layer and the descriptions agents see. A layer's image stage is
built on its parent's (see the Dockerfile), so a child must never change a pin its parent set.

    uv run --frozen python scripts/sandbox_environments.py lock [--upgrade]   # `make lock`
    uv run --frozen python scripts/sandbox_environments.py catalog            # `npm run environments:catalog`

`lock` resolves every layer for linux/arm64 in parent-first order with `uv pip compile`, passing the parent's
requirements.txt as an input, so the child's lock holds every parent pin unchanged plus its own packages. A layer's
optional constraints.txt bounds its transitive dependencies (descendants inherit the result through its lock). Its
optional overrides.txt replaces a dependency's declared requirement on another package (`uv pip compile --overrides`),
for a security fix that an exact upstream pin blocks; the layer installs with --no-deps, so the override holds. A
layer may take a direct dependency from another index (for example a CPU-only build) with `[tool.uv.sources]` naming an
explicit `[[tool.uv.index]]`: uv then resolves only that package there, and the lock records the index's page for the
package as a --find-links line, so the image build finds the same hash-checked files. It also locks
build-requirements.txt (uv and the build backend for packages published only as source distributions). It needs
network access to PyPI and to any such index.

`catalog` writes `lib/sandbox/catalog.json` (read by the CDK app and the tools Lambda's list_environments) and the
environment table in README.md. The tests fail when either is stale.
"""

import argparse
import json
import re
import subprocess
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

SANDBOX_DIR = Path(__file__).resolve().parent.parent
ENVIRONMENTS_DIR = SANDBOX_DIR / "environments"
REPO_DIR = SANDBOX_DIR.parent.parent
CATALOG_FILE = REPO_DIR / "lib" / "sandbox" / "catalog.json"
README_FILE = REPO_DIR / "README.md"
BUILD_REQUIREMENTS_IN = SANDBOX_DIR / "build-requirements.in"

PYTHON_VERSION = "3.13"
# The image is python:3.13-slim-trixie (glibc 2.41) for linux/arm64.
PYTHON_PLATFORM = "aarch64-manylinux_2_40"
# Runtime names are `<projectName>_<id>`: projectName is at most 36 characters and runtime names at most 48.
LAYER_ID = re.compile(r"^[a-z][a-z0-9]{0,10}$")
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([A-Za-z0-9.+!-]+)$")
LOCK_LINE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==(\S+)")

README_BEGIN = "<!-- BEGIN ENVIRONMENTS: generated by `npm run environments:catalog`; do not edit -->"
README_END = "<!-- END ENVIRONMENTS -->"

# Libraries installed as dependencies that are worth telling an agent about, with their import names.
NOTABLE = {
    "matplotlib": "matplotlib",
    "seaborn": "seaborn",
    "plotly": "plotly",
    "statsmodels": "statsmodels",
    "scikit-learn": "sklearn",
    "scikit-image": "skimage",
    "networkx": "networkx",
    "h5py": "h5py",
    "numba": "numba",
    "umap-learn": "umap",
    "pillow": "PIL",
    "requests": "requests",
    "pyarrow": "pyarrow",
    "polars": "polars",
    "dask": "dask",
    "xarray": "xarray",
    "zarr": "zarr",
    "tifffile": "tifffile",
    "joblib": "joblib",
    "biopython": "Bio",
    "anndata": "anndata",
    "python-igraph": "igraph",
    "pyyaml": "yaml",
    "tqdm": "tqdm",
}


def normalize(name: str) -> str:
    """PEP 503 normalized distribution name."""
    return re.sub(r"[-_.]+", "-", name).lower()


@dataclass
class Layer:
    id: str
    title: str
    description: str
    parent: str | None
    deploy: bool
    pins: dict[str, str]
    packages: dict[str, dict[str, str]]
    use_for: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    programs: list[dict[str, Any]] = field(default_factory=list)
    # The package pages of the explicit indexes this layer's [tool.uv.sources] name, for the lock's --find-links.
    find_links: list[str] = field(default_factory=list)

    @property
    def directory(self) -> Path:
        return ENVIRONMENTS_DIR / self.id

    @property
    def lock_file(self) -> Path:
        return self.directory / "requirements.txt"


def _fail(layer: str, message: str) -> None:
    raise ValueError(f"environments/{layer}/pyproject.toml: {message}")


def _load(directory: Path) -> Layer:
    lid = directory.name
    if not LAYER_ID.match(lid):
        _fail(lid, "the directory name must be 1-11 lowercase letters and digits, starting with a letter")
    with open(directory / "pyproject.toml", "rb") as fh:
        data = tomllib.load(fh)
    project = data.get("project", {})
    meta = data.get("tool", {}).get("code-sandbox", {})
    if project.get("name") != f"sandbox-env-{lid}":
        _fail(lid, f"project.name must be sandbox-env-{lid}")
    pins: dict[str, str] = {}
    for dep in project.get("dependencies", []):
        match = PIN.match(dep)
        if not match:
            _fail(lid, f"dependency {dep!r} must be an exact pin (name==version)")
        pins[normalize(match.group(1))] = match.group(2)
    packages = {normalize(k): v for k, v in meta.get("packages", {}).items()}
    if set(packages) != set(pins):
        _fail(lid, "[tool.code-sandbox.packages] must describe exactly the project dependencies")
    for name, info in packages.items():
        if not isinstance(info.get("summary"), str) or not info["summary"]:
            _fail(lid, f"package {name} needs a summary")
    for key in ("title",):
        if not isinstance(meta.get(key), str) or not meta[key]:
            _fail(lid, f"[tool.code-sandbox] needs a {key}")
    if not isinstance(project.get("description"), str) or not project["description"]:
        _fail(lid, "project.description is required: agents see it")
    deploy = meta.get("deploy", True)
    if deploy and not meta.get("use-for"):
        _fail(lid, "a deployed environment needs [tool.code-sandbox] use-for")
    programs = meta.get("programs", [])
    for program in programs:
        if not (program.get("name") and program.get("summary") and isinstance(program.get("check"), list)):
            _fail(lid, "each program needs a name, a summary and a check command")
    return Layer(
        id=lid,
        title=meta["title"],
        description=project["description"],
        parent=meta.get("parent"),
        deploy=bool(deploy),
        pins=pins,
        packages=packages,
        use_for=list(meta.get("use-for", [])),
        notes=list(meta.get("notes", [])),
        programs=list(programs),
        find_links=_find_links(lid, data.get("tool", {}).get("uv", {}), pins),
    )


def _find_links(lid: str, uv: dict[str, Any], pins: dict[str, str]) -> list[str]:
    """The --find-links pages for the direct dependencies a layer takes from another index.

    Each [tool.uv.sources] entry must name an explicit HTTPS index ([[tool.uv.index]] with `explicit = true`), so uv
    takes only that package from it, and must be one of the layer's pinned dependencies. The page is the package's
    PEP 503 simple page on that index, which lists nothing but that package's files.
    """
    indexes = {}
    for index in uv.get("index", []):
        if not (index.get("explicit") is True and str(index.get("url", "")).startswith("https://")):
            _fail(lid, "every [[tool.uv.index]] must be explicit and use https")
        indexes[index["name"]] = index["url"].rstrip("/")
    pages = []
    for name, source in uv.get("sources", {}).items():
        if set(source) != {"index"} or source["index"] not in indexes:
            _fail(lid, f"[tool.uv.sources] {name} must name one of the layer's [[tool.uv.index]] entries")
        if normalize(name) not in pins:
            _fail(lid, f"[tool.uv.sources] {name} must be a pinned dependency of the layer")
        pages.append(f"{indexes[source['index']]}/{normalize(name)}/")
    return pages


def load_layers() -> list[Layer]:
    """Every layer, parents before children (then by ID)."""
    layers = {d.name: _load(d) for d in sorted(ENVIRONMENTS_DIR.iterdir()) if (d / "pyproject.toml").is_file()}
    roots = [lid for lid, layer in layers.items() if layer.parent is None]
    if len(roots) != 1:
        raise ValueError(f"exactly one root layer (without a parent) is required, found {roots}")
    for layer in layers.values():
        if layer.parent is not None and layer.parent not in layers:
            _fail(layer.id, f"unknown parent {layer.parent!r}")
    ordered: list[Layer] = []
    frontier = roots
    while frontier:
        ordered.extend(layers[lid] for lid in frontier)
        frontier = sorted(lid for lid, layer in layers.items() if layer.parent in frontier)
    if len(ordered) != len(layers):
        raise ValueError("the layer parents form a cycle")
    return ordered


def lineage(layer: Layer, layers: list[Layer]) -> list[Layer]:
    """The layer's ancestors and the layer itself, root first."""
    by_id = {item.id: item for item in layers}
    chain = [layer]
    while chain[0].parent is not None:
        chain.insert(0, by_id[chain[0].parent])
    return chain


def read_lock(path: Path) -> dict[str, str]:
    """Normalized name -> version of every pinned distribution in a hashed requirements file."""
    pins: dict[str, str] = {}
    for line in path.read_text().splitlines():
        match = LOCK_LINE.match(line)
        if match:
            pins[normalize(match.group(1))] = match.group(2)
    return pins


