def catalog() -> dict[str, Any]:
    layers = load_layers()
    environments = []
    for layer in layers:
        chain = lineage(layer, layers)
        installed = read_lock(layer.lock_file)
        packages = [
            {
                "name": name,
                "version": installed[name],
                **({"import": info["import"]} if info.get("import") else {}),
                "summary": info["summary"],
                "layer": item.id,
            }
            for item in chain
            for name, info in item.packages.items()
        ]
        listed = {p["name"] for p in packages}
        environments.append(
            {
                "id": layer.id,
                "title": layer.title,
                "description": layer.description,
                "parent": layer.parent,
                "deploy": layer.deploy,
                "lineage": [item.id for item in chain],
                "use_for": layer.use_for,
                "notes": layer.notes,
                "packages": packages,
                "programs": [{**program, "layer": item.id} for item in chain for program in item.programs],
                "also_installed": [
                    {"name": name, "version": installed[name], "import": NOTABLE[name]}
                    for name in sorted(installed)
                    if name in NOTABLE and name not in listed
                ],
                "installed": dict(sorted(installed.items())),
            }
        )
    return {"python_version": PYTHON_VERSION, "platform": "linux/arm64", "environments": environments}


def render_catalog(data: dict[str, Any]) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def render_readme_table(data: dict[str, Any]) -> str:
    rows = [
        "| Environment | Purpose | Packages (exact versions in `list_environments`) |",
        "| --- | --- | --- |",
    ]
    root = data["environments"][0]["id"]
    for env in data["environments"]:
        if not env["deploy"]:
            continue
        own = [p for p in env["packages"] if p["layer"] != root or env["id"] == root]
        packages = ", ".join(f"{p['name']} {p['version']}" for p in own)
        if env["id"] != root:
            packages = f"`{root}` + {packages}"
        rows.append(f"| `{env['id']}` | {env['title']} | {packages} |")
    return "\n".join(rows) + "\n"


def updated_readme(text: str, table: str) -> str:
    start, end = text.find(README_BEGIN), text.find(README_END)
    if start < 0 or end < start:
        raise ValueError(f"README.md needs the markers {README_BEGIN!r} and {README_END!r}")
    return text[: start + len(README_BEGIN)] + "\n\n" + table + "\n" + text[end:]


def write_catalog() -> None:
    data = catalog()
    CATALOG_FILE.write_text(render_catalog(data))
    README_FILE.write_text(updated_readme(README_FILE.read_text(), render_readme_table(data)))
    print(f"wrote {CATALOG_FILE.relative_to(REPO_DIR)} and the README environment table", file=sys.stderr)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    lock_parser = sub.add_parser("lock", help="resolve every layer's requirements.txt (needs PyPI access)")
    lock_parser.add_argument("--upgrade", action="store_true", help="allow newer versions of unpinned dependencies")
    sub.add_parser("catalog", help="write lib/sandbox/catalog.json and the README environment table")
    args = parser.parse_args()
    if args.command == "lock":
        lock(args.upgrade)
    else:
        write_catalog()


if __name__ == "__main__":
    main()
