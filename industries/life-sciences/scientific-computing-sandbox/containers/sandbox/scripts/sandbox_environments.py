# lock


def _compile(
    inputs: list[Path],
    output: Path,
    upgrade: bool,
    constraints: Path | None = None,
    overrides: Path | None = None,
    find_links: list[str] | None = None,
) -> None:
    command = [
        "uv",
        "pip",
        "compile",
        *(str(p.relative_to(SANDBOX_DIR)) for p in inputs),
        "--generate-hashes",
        "--python-version",
        PYTHON_VERSION,
        "--python-platform",
        PYTHON_PLATFORM,
        "--custom-compile-command",
        "make lock",
        "--quiet",
        "-o",
        str(output.relative_to(SANDBOX_DIR)),
    ]
    if upgrade:
        command.append("--upgrade")
    if constraints is not None and constraints.is_file():
        command += ["--constraints", str(constraints.relative_to(SANDBOX_DIR))]
    if overrides is not None and overrides.is_file():
        command += ["--overrides", str(overrides.relative_to(SANDBOX_DIR))]
    for page in find_links or []:
        # uv takes the hashes from the explicit index; the --find-links line it writes tells the install where the
        # files are.
        command += ["--find-links", page, "--emit-find-links"]
    print(f"locking {output.relative_to(SANDBOX_DIR)}", file=sys.stderr)
    subprocess.run(command, cwd=SANDBOX_DIR, check=True)


def lock(upgrade: bool) -> None:
    _compile([BUILD_REQUIREMENTS_IN], SANDBOX_DIR / "build-requirements.txt", upgrade)
    layers = load_layers()
    by_id = {layer.id: layer for layer in layers}
    for layer in layers:
        inputs = [by_id[layer.parent].lock_file] if layer.parent else []
        constraints = layer.directory / "constraints.txt"
        overrides = layer.directory / "overrides.txt"
        _compile(
            [*inputs, layer.directory / "pyproject.toml"],
            layer.lock_file,
            upgrade,
            constraints,
            overrides,
            layer.find_links,
        )


